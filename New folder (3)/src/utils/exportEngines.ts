// Helper to format seconds to timecode HH:MM:SS:FF or MM:SS
export function formatTimecode(seconds: number, fps: number = 30): string {
  const s = Math.max(0, seconds);
  const hrs = Math.floor(s / 3600);
  const mins = Math.floor((s % 3600) / 60);
  const secs = Math.floor(s % 60);
  const frames = Math.floor((s % 1) * fps);

  const pad = (n: number) => n.toString().padStart(2, '0');
  if (hrs > 0) {
    return `${pad(hrs)}:${pad(mins)}:${pad(secs)}:${pad(frames)}`;
  }
  return `${pad(mins)}:${pad(secs)}:${pad(frames)}`;
}

export function formatSecondsOnly(seconds: number): string {
  const s = Math.max(0, seconds);
  const mins = Math.floor(s / 60);
  const secs = Math.floor(s % 60);
  return `${mins}:${secs.toString().padStart(2, '0')}`;
}

// Generate CMX 3600 EDL (Industry Standard Edit Decision List supported by Premiere, DaVinci, FCP)
export function generateCMX3600EDL(reel: HighlightReel, footage: RawFootage): string {
  const lines: string[] = [
    `TITLE: ${reel.title.toUpperCase().replace(/[^A-Z0-9_ ]/g, '')}`,
    `FCM: NON-DROP FRAME`,
    ``,
  ];

  let recordStartSec = 0;

  reel.items.forEach((item, index) => {
    const eventNum = (index + 1).toString().padStart(3, '0');
    const reelName = 'AX'; // Auxiliary reel identifier
    const track = 'V     C'; // Video, Cut

    const sourceIn = formatTimecode(item.startTime);
    const sourceOut = formatTimecode(item.endTime);
    const recordIn = formatTimecode(recordStartSec);
    const recordOut = formatTimecode(recordStartSec + item.duration);

    lines.push(`${eventNum}  ${reelName}      ${track}        ${sourceIn} ${sourceOut} ${recordIn} ${recordOut}`);
    lines.push(`* FROM CLIP NAME: ${footage.title}`);
    lines.push(`* HIGHLIGHT: ${item.title}`);
    lines.push(`* VIRAL SCORE: ${item.viralScore}%`);
    if (item.hookText) {
      lines.push(`* HOOK CAPTION: "${item.hookText}"`);
    }
    lines.push(``);

    recordStartSec += item.duration;
  });

  return lines.join('\n');
}

// Generate CapCut / DaVinci compatible JSON Project
export function generateCapCutJsonProject(reel: HighlightReel, footage: RawFootage): string {
  const project = {
    platform: 'AutoReel Studio AI',
    version: '2.4.0',
    generatedAt: new Date().toISOString(),
    projectSettings: {
      name: reel.title,
      aspectRatio: reel.aspectRatio,
      width: reel.aspectRatio === '9:16' ? 1080 : reel.aspectRatio === '16:9' ? 1920 : 1080,
      height: reel.aspectRatio === '9:16' ? 1920 : reel.aspectRatio === '16:9' ? 1080 : 1080,
      fps: 30,
      totalDurationSeconds: reel.items.reduce((acc, i) => acc + i.duration, 0),
    },
    rawSource: {
      title: footage.title,
      sourceUrl: footage.videoUrl,
      resolution: footage.resolution,
    },
    tracks: [
      {
        type: 'video_main',
        name: 'A-Roll Highlights',
        clips: reel.items.map((item, idx) => ({
          trackIndex: idx,
          name: item.title,
          sourceIn: item.startTime,
          sourceOut: item.endTime,
          timelineDuration: item.duration,
          transitionIn: item.transitionIn,
          zoomScale: item.zoomScale,
          viralScore: item.viralScore,
          hookHeadline: item.hookText || null,
        })),
      },
      {
        type: 'subtitles',
        style: reel.subtitleStyle,
        name: 'AI Kinetic Captions',
        autoGenerated: true,
      },
      {
        type: 'audio_music',
        name: reel.backgroundMusic,
        volume: reel.musicVolume,
      },
    ],
  };

  return JSON.stringify(project, null, 2);
}

// Trigger file download helper in browser
export function downloadTextFile(filename: string, content: string, mimeType: string = 'text/plain') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
